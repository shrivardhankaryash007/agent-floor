"""First-run setup for an agent-floor policy and pinned sandbox runtime."""

import json
import os
import shutil
import subprocess
import tomllib
from collections.abc import Callable, Sequence
from datetime import date
from pathlib import Path
from typing import TextIO

from agent_floor.errors import FloorUnavailableError
from agent_floor.run import find_srt

SUPPORTED_CLIS: tuple[str, ...] = ("claude", "codex", "agy")


def detect_clis(*, which: Callable[[str], str | None] = shutil.which) -> list[str]:
    """Return installed supported CLIs in stable order."""
    return [name for name in SUPPORTED_CLIS if which(name)]


def _project_path(path: Path) -> str:
    """Format a project directory as home-relative where possible."""
    resolved = path.resolve()
    try:
        relative = resolved.relative_to(Path.home().resolve())
    except ValueError:
        return str(resolved)
    return "~/" + relative.as_posix()


def render_policy(project_dirs: Sequence[Path], clis: Sequence[str], *, today: date) -> str:
    """Render a valid starter policy for selected CLIs and project directories."""
    for cli_name in clis:
        if cli_name not in SUPPORTED_CLIS:
            raise ValueError(f"unknown CLI: {cli_name}")
    if not clis:
        raise ValueError("at least one CLI is required")
    lines = [
        f"# Generated by agent-floor init on {today}; built-in protections apply on top.",
        "# To add a host, copy a [[rules]] block and change its id, host and reason.",
        "version = 1",
        "project_dirs = ["
        + ", ".join(json.dumps(_project_path(path)) for path in project_dirs)
        + "]",
        'env_allow = ["EDITOR", "COLORTERM", "NO_COLOR"]',
        "allow_pty = true",
        "# S1 Codex compatibility; residual hole: weaker network isolation.",
        f"weaker_network_isolation = {'true' if 'codex' in clis else 'false'}",
        "# S1 Antigravity compatibility; residual hole: local binding.",
        f"allow_local_binding = {'true' if 'agy' in clis else 'false'}",
        "",
    ]
    rules: list[tuple[str, str, str, str]] = [
        (
            "github",
            "amber",
            "github.com",
            "git fetch and push; logged because push is an exfil path",
        ),
        ("pypi", "amber", "pypi.org", "package index; logged for typosquat review"),
        (
            "pypi-files",
            "amber",
            "files.pythonhosted.org",
            "package downloads; logged for typosquat review",
        ),
    ]
    cli_rules = {
        "claude": [
            ("claude-api", "green", "api.anthropic.com", "Claude Code model API"),
            ("claude-ai", "green", "claude.ai", "Claude Code account and OAuth"),
            ("claude-platform", "amber", "platform.claude.com", "Claude OAuth login and refresh"),
            ("claude-console", "amber", "console.anthropic.com", "Claude OAuth login and refresh"),
        ],
        "codex": [
            ("codex-api", "green", "api.openai.com", "Codex model API"),
            ("codex-chatgpt", "green", "chatgpt.com", "Codex account service"),
            ("codex-auth", "green", "auth.openai.com", "Codex authentication"),
        ],
        "agy": [
            ("agy-googleapis", "green", "*.googleapis.com", "Antigravity Google API"),
            (
                "agy-googleusercontent",
                "green",
                "*.googleusercontent.com",
                "Antigravity Google content",
            ),
            ("agy-gstatic", "green", "*.gstatic.com", "Antigravity static assets"),
            ("agy-accounts", "green", "accounts.google.com", "Antigravity account login"),
        ],
    }
    present = {host for _, _, host, _ in rules}
    for cli_name in clis:
        for rule in cli_rules[cli_name]:
            if rule[2] not in present:
                rules.append(rule)
                present.add(rule[2])
    for rule_id, tier, host, reason in rules:
        # JSON basic strings use the same escapes as TOML basic strings.
        tomllib.loads(f"v = {json.dumps(host)}")
        lines.extend(
            (
                "[[rules]]",
                f"id = {json.dumps(rule_id)}",
                f"tier = {json.dumps(tier)}",
                'kind = "net"',
                f"pattern = {json.dumps(host)}",
                f"added = {today.isoformat()}",
                f"reason = {json.dumps(reason)}",
                "",
            )
        )
    return "\n".join(lines)


def ensure_srt(
    tools_dir: Path,
    *,
    find: Callable[[], Path] = find_srt,
    runner: Callable[..., subprocess.CompletedProcess[bytes]] = subprocess.run,
    which: Callable[[str], str | None] = shutil.which,
) -> bool:
    """Install pinned tool dependencies if srt is absent; never raise."""
    try:
        find()
    except FloorUnavailableError:
        pass  # fall through to the install
    else:
        return True
    try:
        npm = which("npm")
        if npm is None:
            return False
        result = runner([npm, "ci", "--ignore-scripts"], cwd=tools_dir, check=False)
        if result.returncode != 0:
            return False
        find()
        return True
    except (FloorUnavailableError, OSError):
        return False


def run_init(
    project_dirs: Sequence[Path],
    clis: Sequence[str],
    *,
    config_path: Path,
    today: date,
    ensure_srt: Callable[[], bool],
    doctor: Callable[[], int],
    out: TextIO,
) -> int:
    """Install if needed, create a policy without clobbering, then report run commands."""
    if not ensure_srt():
        print("srt install failed; manual fix: cd tools && npm ci --ignore-scripts", file=out)
    config_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        descriptor = os.open(config_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        print(f"policy unchanged: {config_path}", file=out)
    else:
        try:
            with os.fdopen(descriptor, "w") as target:
                target.write(render_policy(project_dirs, clis, today=today))
        except BaseException:
            config_path.unlink(missing_ok=True)
            raise
        print(f"wrote {config_path}", file=out)
    for cli_name in clis:
        suffix = " -s danger-full-access" if cli_name == "codex" else ""
        print(f"agent-floor run -- {cli_name}{suffix}", file=out)
    return doctor()
